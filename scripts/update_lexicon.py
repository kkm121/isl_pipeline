full_dict = {}
for word in CLASSROOM_VOCABULARY_200:
    if word in translations:
        h, t, te, b, m = translations[word]
    else:
        title = word.replace("_", " ").title()
        h, t, te, b, m = (title, title, title, title, title)
    full_dict[word] = {
        "hin_Deva": h,
        "tam_Taml": t,
        "tel_Telu": te,
        "ben_Beng": b,
        "mar_Mrai": m,
    }

code_str = "OFFLINE_CLASSROOM_LEXICON: Dict[str, Dict[str, str]] = {\n"
for k, v in full_dict.items():
    code_str += f'    "{k}": {{\n'
    for lk, lv in v.items():
        code_str += f'        "{lk}": "{lv}",\n'
    code_str += "    },\n"
code_str += "}\n"

path = "src/inference/translation_tts.py"
with open(path, "r", encoding="utf-8") as f:
    content = f.read()

pattern = r"OFFLINE_CLASSROOM_LEXICON: Dict\[str, Dict\[str, str\]\] = \{.*?\n\}\n"
new_content = re.sub(pattern, code_str, content, flags=re.DOTALL)

with open(path, "w", encoding="utf-8") as f:
    f.write(new_content)

print(f"Updated {path} with {len(full_dict)} lexicon entries.")
